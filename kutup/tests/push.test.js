import { test } from "node:test";
import assert from "node:assert/strict";
import { createECDH } from "node:crypto";
import {
  base64url,
  encryptPayload,
  generateVapidKeys,
  vapidAuthorization,
} from "../server/push.js";
import { pushReceiver, verifyVapid } from "./helpers.js";

test("payload encryption round-trips through the reference aes128gcm decoder", async () => {
  const receiver = pushReceiver();
  const message = JSON.stringify({ title: "Aylin kütüpte! 📚", body: "Bahçe" });
  const body = await encryptPayload(
    receiver.subscription("https://fcm.googleapis.com/fcm/send/x"),
    message,
  );
  assert.equal(receiver.decrypt(body), message);
});

test("VAPID tokens are valid ES256 JWTs for the push service origin", async () => {
  const keys = await generateVapidKeys();
  assert.equal(base64url.decode(keys.publicKey).length, 65);
  const endpoint = "https://web.push.apple.com/QGuQyavXutnMH";
  const claims = await verifyVapid(
    await vapidAuthorization(endpoint, keys, "https://kutup.example"),
    endpoint,
    keys.publicKey,
  );
  assert.equal(claims.sub, "https://kutup.example");
});

test("keys generated by the old web-push package still sign", async () => {
  // Format written by web-push's generateVAPIDKeys(): raw public key + raw d.
  const ecdh = createECDH("prime256v1");
  ecdh.generateKeys();
  const keys = {
    publicKey: ecdh.getPublicKey().toString("base64url"),
    privateKey: ecdh.getPrivateKey().toString("base64url"),
  };
  const endpoint = "https://updates.push.services.mozilla.com/wpush/v2/x";
  await verifyVapid(
    await vapidAuthorization(endpoint, keys, "mailto:test@example.com"),
    endpoint,
    keys.publicKey,
  );
});
