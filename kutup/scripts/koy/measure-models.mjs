// n46 köy v2: measures every catalogue drawing at its pinned village scale
// and writes the numbers the server plans with (shared/koy2/modelData.js).
//   node scripts/koy/measure-models.mjs           write
//   node scripts/koy/measure-models.mjs --check   compare only (atlas test)
// Local coordinates of facing 0 (door on the +y wall); facing 1 swaps x and y.
// ground: what touches the ground (z ≤ 0.32: plinth, steps, yard fittings);
// over:   everything drawn (eaves, balconies, sails, masts); h: the top.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildingSVG, drawnSize, spec, useSVG } from "../../src/iso.js";
import { CATALOG } from "../../shared/catalog.js";

const r2 = (v) => Math.round(v * 100) / 100;
export const SEEDS = [7, 101, 9973];

/** Extents of one drawing; the scale is the model's full own size (never squeezed). */
export function measure(item, seed = 7, scale = null) {
  useSVG();
  const k = scale ?? (item.look?.special ? drawnSize(item.id).k : 1);
  const sp = spec(item.kind, seed, item.id, item.look?.special ? { scale: k } : {});
  const all = [Infinity, Infinity, -Infinity, -Infinity],
    low = [Infinity, Infinity, -Infinity, -Infinity];
  let h = 0;
  const take = (b, x, y) => {
    b[0] = Math.min(b[0], x);
    b[1] = Math.min(b[1], y);
    b[2] = Math.max(b[2], x);
    b[3] = Math.max(b[3], y);
  };
  const P = (x, y, z) => {
    take(all, x, y);
    if (z <= 0.32) take(low, x, y);
    h = Math.max(h, z);
    return [(x - y) * 0.866, (x + y) * 0.5 - z];
  };
  buildingSVG(P, sp, seed, { detail: 2, shadowP: () => [0, 0] });
  return { kind: item.kind, k: r2(k), hw: r2(sp.hw), ground: low.map(r2), over: all.map(r2), h: r2(h) };
}

/** The contract numbers: the union over a few seeds (roof colour, chimney, lit windows vary). */
export function measureAll() {
  const out = {};
  for (const item of CATALOG) {
    const runs = SEEDS.map((s) => measure(item, s));
    const u = (key) => [Math.min(...runs.map((r) => r[key][0])), Math.min(...runs.map((r) => r[key][1])), Math.max(...runs.map((r) => r[key][2])), Math.max(...runs.map((r) => r[key][3]))];
    out[item.id] = { kind: item.kind, k: runs[0].k, hw: runs[0].hw, ground: u("ground"), over: u("over"), h: Math.max(...runs.map((r) => r.h)) };
  }
  return out;
}

function main() {
  const data = measureAll();
  const body = Object.entries(data)
    .map(([id, m]) => `  ${id}: { kind: "${m.kind}", k: ${m.k}, hw: ${m.hw}, ground: [${m.ground.join(", ")}], over: [${m.over.join(", ")}], h: ${m.h} },`)
    .join("\n");
  const text = `// Generated by scripts/koy/measure-models.mjs from the drawings (src/iso.js,
// src/special.js) at each model's pinned village scale. Do not edit by hand:
// a changed drawing needs a new geometry version (shared/koy2/models.js).
// Local coordinates of facing 0; ground = z ≤ 0.32, over = all drawn, h = top.
export const MODEL_DATA = {
${body}
};
`;
  if (process.argv.includes("--check")) {
    console.log(JSON.stringify(data));
    return;
  }
  writeFileSync(fileURLToPath(new URL("../../shared/koy2/modelData.js", import.meta.url)), text);
  console.log(`${Object.keys(data).length} models measured`);
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
